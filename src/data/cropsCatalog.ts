export function buildSampleMarketDataset(referenceTimestamp = new Date().toISOString()): MarketDatasetResponse {
  const quotes: MarketQuote[] = [];

  for (const crop of CROPS_CATALOG) {
    const matrix = MANDI_PRICE_MATRIX[crop.id] ?? {};
    for (const [marketId, stats] of Object.entries(matrix)) {
      const loc = MARKET_LOCATIONS.find((m) => m.id === marketId);
      if (!loc) continue;
      quotes.push({
        id: `${crop.id}__${marketId}`,
        cropId: crop.id,
        marketId,
        marketName: loc.name,
        city: loc.city,
        state: loc.state,
        variety: crop.variety.en,
        grade: crop.qualityGrade.en,
        minPricePerKg: Math.max(1, stats.modal - stats.spread),
        maxPricePerKg: stats.modal + stats.spread,
        modalPricePerKg: stats.modal,
        modalPricePerQuintal: stats.modal * 100,
        demand: stats.demand,
        availableQuantityKg: stats.qty,
        lastUpdated: referenceTimestamp,
        source: 'sample-reference',
        sourceLabel: 'Sample Reference Dataset (Illustrative Baseline)',
      });
    }
  }

  return {
    source: 'sample-reference',
    sourceLabel: 'Sample Reference Dataset (Illustrative Baseline)',
    fetchedAt: referenceTimestamp,
    note: 'Displaying illustrative reference mandi baselines. Configure DATA_GOV_IN_API_KEY on the server to fetch live AGMARKNET feeds.',
    quotes,
  };
}
